import { Outcome, PLANNED_FIELDS, RowPlan } from './plan';

// Rows per UPDATE statement, so no single statement in the migration gets too large.
const ROWS_PER_STATEMENT = 500;
// The Drizzle schema declares city, street, zipcode, unit, secondaryUnit and saleDate as varchar(256) (prod has text);
// refuse longer values so the migration can't fail on a database that matches the schema.
const VARCHAR_LENGTH = 256;

const OUTCOMES: Outcome[] = ['known town', 'case boundary', 'glued suffix', 'blank', 'unresolved'];

const controlCharacterEscapes: Record<string, string> = { '\\': '\\\\', '\r': '\\r', '\n': '\\n', '\t': '\\t' };

/**
 * A value as an SQL literal: `NULL`, or a single-quoted string with its quotes doubled. A value with a carriage
 * return, newline or tab becomes an `E'…'` escape string, so the migration file holds no raw control characters.
 */
export const sqlLiteral = (value: string | null) => {
  if (value === null) {
    return 'NULL';
  }

  const quoted = value.replace(/'/g, "''");

  return /[\r\n\t]/.test(value)
    ? `E'${quoted.replace(/[\\\r\n\t]/g, (character) => controlCharacterEscapes[character])}'`
    : `'${quoted}'`;
};

const updateStatement = (plans: RowPlan[]) => {
  const rows = plans.map(({ row, values }) =>
    [row.id, row.address, row.city, row.saleDate, ...PLANNED_FIELDS.map((field) => values[field])]
      .map(sqlLiteral)
      .join(', '),
  );

  return [
    'UPDATE "Listing" AS "l"',
    `SET ${PLANNED_FIELDS.map((field) => `"${field}" = "v"."${field}"`).join(', ')}`,
    'FROM (VALUES',
    rows.map((row) => `  (${row})`).join(',\n'),
    `) AS "v"("id", "oldAddress", "oldCity", "oldSaleDate", ${PLANNED_FIELDS.map((field) => `"${field}"`).join(', ')})`,
    'WHERE "l"."id" = "v"."id"',
    '  AND "l"."address" IS NOT DISTINCT FROM "v"."oldAddress"',
    '  AND "l"."city" IS NOT DISTINCT FROM "v"."oldCity"',
    '  AND "l"."saleDate" IS NOT DISTINCT FROM "v"."oldSaleDate";',
  ].join('\n');
};

/**
 * The custom migration for every plan with changes: guarded UPDATEs that apply only while the row's
 * address, city and sale date still equal the exported values, so deleted, edited or already-repaired rows are skipped.
 */
export const toMigrationSql = (plans: RowPlan[]) => {
  const updates = plans.filter((plan) => plan.changes.length > 0);

  for (const { row, values } of updates) {
    for (const field of PLANNED_FIELDS) {
      if (field !== 'address' && (values[field]?.length ?? 0) > VARCHAR_LENGTH) {
        throw new Error(`Listing ${row.id}: planned ${field} is longer than ${VARCHAR_LENGTH} characters`);
      }
    }
  }

  const statements: string[] = [];

  for (let i = 0; i < updates.length; i += ROWS_PER_STATEMENT) {
    statements.push(updateStatement(updates.slice(i, i + ROWS_PER_STATEMENT)));
  }

  const header = [
    '-- Generated by backend/scripts/backfillListingAddresses from a read-only export of prod. Do not edit by hand:',
    '-- regenerate it instead. Repairs the address fields of listings scraped before adapt-scraper-to-civilview,',
    '-- and trims scraper whitespace from "address" and "saleDate". Each row updates only while its exported',
    '-- "address", "city" and "saleDate" are unchanged, so re-running it changes nothing.',
  ].join('\n');

  return statements.length ? `${header}\n${statements.join('\n--> statement-breakpoint\n')}\n` : `${header}\n`;
};

const csvField = (value: string | null) => {
  if (value === null) {
    return 'NULL';
  }

  return /[",\r\n]/.test(value) || value !== value.trim() ? `"${value.replace(/"/g, '""')}"` : value;
};

/**
 * The review report: one line per planned update and per blank or unresolved row, with every field's old and new
 * value. `NULL` is a database NULL; an empty field is ''.
 */
export const toReportCsv = (plans: RowPlan[]) => {
  const header = [
    'id',
    'county',
    'outcome',
    'changed',
    ...PLANNED_FIELDS.flatMap((field) => [`old ${field}`, `new ${field}`]),
  ];
  const lines = plans
    .filter((plan) => plan.changes.length > 0 || plan.outcome === 'blank' || plan.outcome === 'unresolved')
    .map(({ row, outcome, values, changes }) => [
      row.id,
      row.county,
      outcome,
      changes.join(' '),
      ...PLANNED_FIELDS.flatMap((field) => [row[field], values[field]]),
    ]);

  return `${[header, ...lines].map((line) => line.map(csvField).join(',')).join('\n')}\n`;
};

export interface Summary {
  exported: number;
  alreadyCorrect: number;
  plannedUpdates: number;
  /** Planned updates by outcome; blank and unresolved rows can still need an update for their whitespace or city. */
  plannedByOutcome: Record<Outcome, number>;
  rowsByOutcome: Record<Outcome, number>;
  city: { filled: number; corrected: number; cleared: number; unchanged: number };
}

export const summarize = (plans: RowPlan[]): Summary => {
  const count = () => Object.fromEntries(OUTCOMES.map((outcome) => [outcome, 0])) as Record<Outcome, number>;
  const summary: Summary = {
    exported: plans.length,
    alreadyCorrect: 0,
    plannedUpdates: 0,
    plannedByOutcome: count(),
    rowsByOutcome: count(),
    city: { filled: 0, corrected: 0, cleared: 0, unchanged: 0 },
  };

  for (const { row, outcome, values, changes } of plans) {
    summary.rowsByOutcome[outcome]++;

    if (changes.length) {
      summary.plannedUpdates++;
      summary.plannedByOutcome[outcome]++;
    } else {
      summary.alreadyCorrect++;
    }

    if (values.city === row.city) {
      summary.city.unchanged++;
    } else if (values.city === null) {
      summary.city.cleared++;
    } else if (row.city) {
      summary.city.corrected++;
    } else {
      summary.city.filled++;
    }
  }

  return summary;
};
